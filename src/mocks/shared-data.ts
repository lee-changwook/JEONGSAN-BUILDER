export function makeDates(dayOfWeek: string): string[] {
  const dayMap: Record<string, number[]> = {
    '월수': [3, 5, 10, 12, 17, 19, 24, 26],
    '화목': [4, 6, 11, 13, 18, 20, 25, 27],
    '월수금': [3, 5, 7, 10, 12, 14, 17, 19, 21, 24, 26, 28],
    '수토': [5, 8, 12, 15, 19, 22, 26, 29],
  };
  const days = dayMap[dayOfWeek] ?? [3, 5, 10, 12, 17, 19, 24, 26];
  return days.map((d) => `2026-03-${String(d).padStart(2, '0')}`);
}

